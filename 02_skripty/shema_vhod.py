    # дверь санузла 700 — открывается наружу, в коридор
    ax.add_patch(Arc((1.945, 7.04), 1.4, 1.4, theta1=0, theta2=90, color="#B03A2E", lw=1, ls="--"))
    ax.text(2.30, 7.25, NL.join(["дверь с/у 700", "(наружу)"]), fontsize=8, color="#B03A2E")
    # блок выключателей санузла + терморегулятор
    R(ax, 1.945, 7.79, 2.00, 7.94, "#2E7D4F", "", ec="#2E7D4F"); ax.text(2.04, 7.86, "выкл. с/у 3-кл. + t° пола, h 900", fontsize=7.5, color="#2E7D4F", va="center")
