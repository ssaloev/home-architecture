    legs(ax, WX0 + 0.40, 8.0, WX1 - 0.24, 9.30, NL.join(["проход", mm(WX1 - 0.24 - WX0 - 0.40)]))
    legs(ax, 1.945, 6.75, 3.455, 7.00, "коридор " + mm(7.909 - 6.672) + " — к комнатам")
    # подписи помещений
    ax.text(3.40, 6.62, "гостиная ↑", fontsize=8, color="#555", ha="right")
    ax.text(4.0, 7.62, NL.join(["ванная", "→"]), fontsize=8, color="#555")
