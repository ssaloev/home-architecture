    # шкаф хозяев 400×750 и место гостей (скамья + штанга) — левая стена
    R(ax, WX0, 7.95, WX0 + 0.40, 8.70, WH, NL.join(["шкаф", "хозяев", "400×750", "до потолка"]), 8.5, ec="#333")
    R(ax, WX0, 8.72, WX0 + 0.40, 9.30, "#E9E1D4", NL.join(["гости:", "скамья", "+ штанга"]), 8, ec="#333")
    # обувница 240 + зеркало — правая стена
    R(ax, WX1 - 0.24, 8.45, WX1, 9.25, GR, NL.join(["обув-", "ница", "240", "+ зер-", "кало"]), 7.5, col="white", ec="#333")
