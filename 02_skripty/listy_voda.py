def block(x, y, head, lines, width=58, fs=24, col=INK):
    label(x, y, head, 28, col, bold=True); y += 42
    for ln in lines:
        first = True
        for part in textwrap.wrap(ln, width):
            label(x + (0 if first else 22), y, part, fs, INK); y += 33; first = False
        y += 6
    return y


