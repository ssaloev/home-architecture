CB, CH, CK = BLUE, RED, BROWN


def pipe(pts, col=CB, w=7, dash=None):
    d = " ".join(("M" if i == 0 else "L") + f"{x:.0f},{y:.0f}" for i, (x, y) in enumerate(pts))
    A(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{w}" stroke-linejoin="round"' + (f' stroke-dasharray="{dash}"' if dash else "") + '/>')


def unit(cx, cy, t1, t2="", w=180, h=92, fill="#FFFFFF", col=INK):
    A(f'<rect x="{cx-w/2:.0f}" y="{cy-h/2:.0f}" width="{w}" height="{h}" rx="10" fill="{fill}" stroke="{col}" stroke-width="3.5"/>')
    if t2:
        A(f'<text x="{cx:.0f}" y="{cy-6:.0f}" text-anchor="middle" font-size="25" font-weight="bold" fill="{INK}">{t1}</text>')
        A(f'<text x="{cx:.0f}" y="{cy+26:.0f}" text-anchor="middle" font-size="21" fill="{INK}">{t2}</text>')
    else:
        A(f'<text x="{cx:.0f}" y="{cy+9:.0f}" text-anchor="middle" font-size="25" font-weight="bold" fill="{INK}">{t1}</text>')


def label(x, y, t, fs=22, col=INK, anchor="start", bold=False):
    A(f'<text x="{x:.0f}" y="{y:.0f}" text-anchor="{anchor}" font-size="{fs}"' + (' font-weight="bold"' if bold else "") + f' fill="{col}">{t}</text>')


def num(x, y, n):   # кружок с номером позиции (см. спецификацию справа)
    A(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="19" fill="{ORANGE}"/><text x="{x:.0f}" y="{y+8:.0f}" text-anchor="middle" font-size="22" font-weight="bold" fill="#FFFFFF">{n}</text>')


