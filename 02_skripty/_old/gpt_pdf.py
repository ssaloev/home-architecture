def para(c, x, y, text, size=12, width=110, lead=1.35, font="D"):
    c.setFont(font, size)
    for line in textwrap.wrap(text, width):
        c.drawString(x, y, line); y -= size * lead
    return y

def img(c, path, x, y, w, h):
    im = Image.open(path).convert("RGB")
    im.thumbnail((1800, 1800))
    b = io.BytesIO(); im.save(b, "JPEG", quality=85); b.seek(0)
    iw, ih = im.size; k = min(w / iw, h / ih)
    c.drawImage(ImageReader(b), x + (w - iw * k) / 2, y + (h - ih * k) / 2, iw * k, ih * k)

